function isSafeURL(raw, isImg) {
  if (!raw) return false;
  const norm = raw.replace(/[\u0000-\u0020\u007f-\u009f\s]+/g, "").toLowerCase();
  if (norm.startsWith("javascript:") || norm.startsWith("vbscript:") || norm.startsWith("file:")) {
    return false;
  }
  if (isImg) {
    if (norm.startsWith("data:image/")) return true;
    if (norm.startsWith("http://") || norm.startsWith("https://")) return true;
    return !norm.includes(":");
  }
  if (norm.startsWith("http://") || norm.startsWith("https://") ||
      norm.startsWith("mailto:") || norm.startsWith("tel:") ||
      norm.startsWith("#")) {
    return true;
  }
  const colon = norm.indexOf(":");
  if (colon !== -1) {
    const slash = norm.indexOf("/");
    if (slash === -1 || colon < slash) return false;
  }
  return true;
}

function sanitizeHTML(html) {
  if (!html) return "";
  try {
    const parser = new DOMParser();
    const doc = parser.parseFromString(html, "text/html");
    const badTags = ["script", "iframe", "object", "embed", "link", "form", "meta", "style", "base", "applet", "frame", "frameset"];
    for (const tag of badTags) {
      doc.querySelectorAll(tag).forEach((el) => el.remove());
    }
    doc.querySelectorAll("*").forEach((el) => {
      const attrs = Array.from(el.attributes);
      for (const attr of attrs) {
        const name = attr.name.toLowerCase();
        if (name.startsWith("on") || name === "formaction" || name === "action" || name === "srcdoc") {
          el.removeAttribute(attr.name);
          continue;
        }
        if (name === "href" || name === "xlink:href") {
          if (!isSafeURL(attr.value, false)) {
            el.removeAttribute(attr.name);
          }
        } else if (name === "src") {
          if (el.tagName.toLowerCase() !== "img" || !isSafeURL(attr.value, true)) {
            el.removeAttribute(attr.name);
          }
        }
      }
    });
    return doc.body.innerHTML;
  } catch (e) {
    return html.replace(/<[^>]*>/g, "");
  }
}

async function loadBookData() {
  try {
    const res = await fetch("/api/watch/book");
    if (!res.ok) throw new Error("Errore API");
    bookData = await res.json();
    render();
    updateStatus(wt("status_synced") + new Date().toLocaleTimeString(watchLang));
  } catch (e) {
    updateStatus(wt("status_waiting"), true);
  }
}

function updateStatus(text, isErr = false) {
  const badge = $("statusBadge");
  const stText = $("statusText");
  stText.textContent = text;
  if (isErr) {
    badge.style.borderColor = "#e74c3c";
    badge.style.color = "#e74c3c";
    badge.querySelector(".pulse-dot").style.background = "#e74c3c";
  } else {
    badge.style.borderColor = "rgba(46, 204, 113, 0.35)";
    badge.style.color = "#2ecc71";
    badge.querySelector(".pulse-dot").style.background = "#2ecc71";
  }
}

function render() {
  if (!bookData || !bookData.book) return;
  const bk = bookData.book;
  $("bookTitle").textContent = bk.title || wt("untitled");
  $("bookAuthor").textContent = bk.author ? `— ${bk.author}` : "";

  // Inietta CSS
  $("dynamicStyleCSS").textContent = bookData.styleCSS || "";
  $("dynamicFontCSS").textContent = bookData.fontCSS || "";
  $("dynamicSceneBreakCSS").textContent = bookData.sceneBreakCSS || "";

  const target = $("contentTarget");
  const scrollPos = $("scrollContainer").scrollTop;

  if (currentMode === "continuous") {
    target.className = "continuous-view rendered-content";
    populateChaptersJump();
    renderContinuous(target);
  } else {
    target.className = "paged-view";
    renderRealPDF(target);
  }

  $("scrollContainer").scrollTop = scrollPos;
}

function populateChaptersJump() {
  const jump = $("jumpChapter");
  const curVal = jump.value;
  jump.innerHTML = '<option value="">' + esc(wt("jump_to_ch")) + '</option>';
  jump.innerHTML += '<option value="page-title">' + esc(wt("cover_title_page")) + '</option>';
  if (bookData && bookData.chapters) {
    bookData.chapters.forEach((ch, idx) => {
      const opt = document.createElement("option");
      opt.value = `ch-${idx}`;
      opt.textContent = `${ch.type && ch.type !== 'chapter' ? '['+ch.type+'] ' : ''}${ch.title || ch.file}`;
      jump.appendChild(opt);
    });
  }
  jump.value = curVal;
}

