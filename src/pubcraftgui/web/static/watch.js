let watchLang = (() => {
  const saved = localStorage.getItem("pubcraft_lang");
  if (saved && WATCH_I18N[saved]) return saved;
  const sys = (navigator.language || "en").slice(0, 2).toLowerCase();
  return WATCH_I18N[sys] ? sys : "en";
})();

function wt(key, params) {
  const dict = WATCH_I18N[watchLang] || WATCH_I18N.en;
  let str = dict[key] || (WATCH_I18N.en && WATCH_I18N.en[key]) || key;
  if (params && typeof params === "object") {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), v);
    }
  }
  return str;
}

